-- media: 미디어/콘텐츠 플랫폼 도메인 데이터셋
-- creators / videos / views / comments / creator_subscriptions

CREATE TABLE creators (
  id              INTEGER PRIMARY KEY,
  name            TEXT    NOT NULL,
  channel         TEXT    NOT NULL UNIQUE,
  category        TEXT    NOT NULL,
  subscriber_cnt  INTEGER NOT NULL DEFAULT 0,
  country         TEXT    NOT NULL DEFAULT 'KR',
  joined_at       TEXT    NOT NULL
);

CREATE TABLE videos (
  id           INTEGER PRIMARY KEY,
  creator_id   INTEGER NOT NULL REFERENCES creators(id),
  title        TEXT    NOT NULL,
  category     TEXT    NOT NULL,
  duration_sec INTEGER NOT NULL,
  view_cnt     INTEGER NOT NULL DEFAULT 0,
  like_cnt     INTEGER NOT NULL DEFAULT 0,
  status       TEXT    NOT NULL DEFAULT 'published',
  published_at TEXT    NOT NULL
);

CREATE TABLE viewer_accounts (
  id         INTEGER PRIMARY KEY,
  nickname   TEXT    NOT NULL,
  created_at TEXT    NOT NULL,
  country    TEXT    NOT NULL DEFAULT 'KR'
);

CREATE TABLE views (
  id                  INTEGER PRIMARY KEY,
  video_id            INTEGER NOT NULL REFERENCES videos(id),
  viewer_id           INTEGER NOT NULL REFERENCES viewer_accounts(id),
  watch_duration_sec  INTEGER NOT NULL,
  device              TEXT    NOT NULL DEFAULT 'mobile',
  watched_at          TEXT    NOT NULL
);

CREATE TABLE comments (
  id         INTEGER PRIMARY KEY,
  video_id   INTEGER NOT NULL REFERENCES videos(id),
  viewer_id  INTEGER NOT NULL REFERENCES viewer_accounts(id),
  content    TEXT    NOT NULL,
  like_cnt   INTEGER NOT NULL DEFAULT 0,
  created_at TEXT    NOT NULL
);

CREATE TABLE creator_subscriptions (
  id          INTEGER PRIMARY KEY,
  viewer_id   INTEGER NOT NULL REFERENCES viewer_accounts(id),
  creator_id  INTEGER NOT NULL REFERENCES creators(id),
  subscribed_at TEXT  NOT NULL,
  UNIQUE (viewer_id, creator_id)
);

